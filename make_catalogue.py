#!/usr/bin/env python3
"""Generate the catalogue workbook (read-only view) from a JSON catalogue directory.

usage: python make_catalogue.py CATALOGUE_DIR OUT.xlsx [--rows N] [--internal] [--pack DIR ...] [--public-only | --no-packs]
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from openpyxl import Workbook
from openpyxl.utils import get_column_letter
from openpyxl.styles import Font, Alignment

from ctm.schema import CATALOGUE, CATALOGUE_CHECKS
from ctm.register import write_register, DEFAULT
from ctm.store import load_catalogue, to_tables
from ctm.common import header, body_cell, add_list_validation, CHK_FONT, BODY, F
from check_catalogue import add_pack_options, pack_args

README = [
    ('Catalogue workbook', 'Source layer (SD, SP, SR) and catalogue layer (CR, LINK_SR_CR, CORR, DECISIONS) of the '
     'Compliance Traceability Methodology (spec v0.3). Projects are generated from this workbook by build_project.py.'),
    ('Generated – do not edit', 'Generated by make_catalogue.py from the JSON catalogue (single source of truth). Edits '
     'made here are lost: change the JSON files and regenerate.'),
    ('REGISTER', 'Every category string, from ctm/vocab.py. Formulas and drop-downs reference it, never literal strings.'),
    ('Drop-downs', 'Columns bound to a register list only accept its labels.'),
    ('Grey italic columns', '"chk:" columns are formula checks for authors (references exist, counting links). Do not edit.'),
    ('Licensed sources', 'SP "Text" of licensed standards is omitted unless generated with --internal (internal use only); SR statements are our own paraphrase (spec § 7).'),
    ('Checks', 'Run check_catalogue.py on the JSON catalogue before releasing a baseline.'),
]


def build(path, data=None, rows=300):
    wb = Workbook()
    ws0 = wb.active
    ws0.title = 'README'
    ws0.column_dimensions['A'].width = 22
    ws0.column_dimensions['B'].width = 110
    ws0['A1'] = 'Compliance Traceability – Catalogue'
    ws0['A1'].font = Font(name=F, size=14, bold=True)
    for i, (a, b) in enumerate(README, 3):
        ws0.cell(row=i, column=1, value=a).font = Font(name=F, bold=True)
        c = ws0.cell(row=i, column=2, value=b); c.font = BODY; c.alignment = Alignment(wrap_text=True, vertical='top')

    write_register(wb, DEFAULT if data is None or 'REGISTER' not in data else data['REGISTER'])

    for sheet, cols in CATALOGUE.items():
        ws = wb.create_sheet(sheet)
        checks = CATALOGUE_CHECKS.get(sheet, [])
        labels = [c.label for c in cols] + [f'chk: {k}' for k in checks]
        widths = [c.width for c in cols] + [11] * len(checks)
        fills = {len(cols) + i + 1: 'D9D9D9' for i in range(len(checks))}
        header(ws, labels, widths, fills)
        recs = (data or {}).get(sheet, [])
        nrows = max(rows, len(recs) + 50)
        for i, rec in enumerate(recs, 2):
            for j, c in enumerate(cols, 1):
                body_cell(ws, i, j, rec.get(c.key, '') or None)
        for j, c in enumerate(cols, 1):
            if c.lst:
                L = get_column_letter(j)
                add_list_validation(ws, c.lst, f'{L}2:{L}{nrows + 1}')
        # check formulas
        L = {c.key: get_column_letter(j) for j, c in enumerate(cols, 1)}
        cat = {s: {c.key: get_column_letter(j) for j, c in enumerate(cc, 1)} for s, cc in CATALOGUE.items()}
        lk = cat['LINK_SR_CR']; lk_counts = get_column_letter(len(CATALOGUE['LINK_SR_CR']) + 1)
        for r in range(2, nrows + 2):
            f = {}
            if sheet == 'SP':
                f['sd_ok'] = f'=IF({L["sp_id"]}{r}="","",IF(COUNTIF(SD!$A:$A,{L["sd_id"]}{r})>0,YN_YES,YN_NO))'
                f['parent_ok'] = (f'=IF(OR({L["sp_id"]}{r}="",{L["parent_sp"]}{r}=""),"",'
                                  f'IF(COUNTIF($A:$A,{L["parent_sp"]}{r})>0,YN_YES,YN_NO))')
            elif sheet == 'SR':
                f['n_counting_links'] = (f'=IF({L["sr_id"]}{r}="","",COUNTIFS(LINK_SR_CR!${lk["sr_id"]}:${lk["sr_id"]},'
                                         f'{L["sr_id"]}{r},LINK_SR_CR!${lk_counts}:${lk_counts},YN_YES))')
            elif sheet == 'CR':
                f['parent_ok'] = (f'=IF(OR({L["cr_id"]}{r}="",{L["parent_cr"]}{r}=""),"",'
                                  f'IF(COUNTIF($A:$A,{L["parent_cr"]}{r})>0,YN_YES,YN_NO))')
                f['n_in_links'] = f'=IF({L["cr_id"]}{r}="","",COUNTIF(LINK_SR_CR!${lk["cr_id"]}:${lk["cr_id"]},{L["cr_id"]}{r}))'
            elif sheet == 'LINK_SR_CR':
                f['counts'] = (f'=IF({L["link_type"]}{r}="","",IF(COUNTIFS(REG_LIST,"LINKTYPE",REG_LABEL,{L["link_type"]}{r},'
                               f'REG_ATTR,YN_YES)>0,YN_YES,YN_NO))')
                f['sr_ok'] = f'=IF({L["sr_id"]}{r}="","",IF(COUNTIF(SR!$A:$A,{L["sr_id"]}{r})>0,YN_YES,YN_NO))'
                f['cr_ok'] = f'=IF({L["cr_id"]}{r}="","",IF(COUNTIF(CR!$A:$A,{L["cr_id"]}{r})>0,YN_YES,YN_NO))'
            elif sheet == 'CORR':
                f['from_ok'] = f'=IF({L["from_sp"]}{r}="","",IF(COUNTIF(SP!$A:$A,{L["from_sp"]}{r})>0,YN_YES,YN_NO))'
                f['to_ok'] = f'=IF({L["to_sp"]}{r}="","",IF(COUNTIF(SP!$A:$A,{L["to_sp"]}{r})>0,YN_YES,YN_NO))'
            for k, chk in enumerate(checks):
                c = ws.cell(row=r, column=len(cols) + k + 1, value=f[chk])
                c.font = CHK_FONT
        ws.freeze_panes = 'B2'
        ws.auto_filter.ref = f'A1:{get_column_letter(len(labels))}{nrows + 1}'
    wb.save(path)
    return path


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('catalogue')
    ap.add_argument('out')
    ap.add_argument('--rows', type=int, default=300)
    ap.add_argument('--internal', action='store_true', help='include verbatim text of licensed sources (internal use only, spec § 7)')
    add_pack_options(ap)
    a = ap.parse_args()
    print(build(a.out, to_tables(load_catalogue(a.catalogue, *pack_args(a)), internal=a.internal), a.rows))
